"""Writes ui/licenses.luau: the open-source crates Pane's app is built from,
with their versions and licenses, for the About dialog.

Run it after changing dependencies: python scripts/licenses.py
"""

import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = "x86_64-pc-windows-msvc"

meta = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET, "--locked"],
        cwd=ROOT,
    )
)
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
workspace = set(meta["workspace_members"])
app = next(i for i in workspace if packages[i]["name"] == "pane-app")

# Everything the app links: normal dependencies, followed from pane-app.
seen, stack = set(), [app]
while stack:
    node = nodes[stack.pop()]
    for dep in node["deps"]:
        if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
            seen.add(dep["pkg"])
            stack.append(dep["pkg"])

crates = sorted(
    {(packages[i]["name"], packages[i]["version"], packages[i].get("license") or "See its repository")
     for i in seen if i not in workspace},
    key=lambda c: (c[0].lower(), c[1]),
)


def lua(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "-- Generated by scripts/licenses.py: the open-source software Pane is built",
    "-- from (the About dialog lists it). Don't edit; run the script again.",
    "",
    "return {",
    '\t{ name = "Geist Mono (font)", version = "", license = "OFL-1.1" },',
]
lines += [f"\t{{ name = {lua(n)}, version = {lua(v)}, license = {lua(l)} }}," for n, v, l in crates]
lines.append("}")
(ROOT / "ui" / "licenses.luau").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(crates)} crates")
